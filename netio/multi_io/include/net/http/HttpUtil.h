#pragma once
// ============================================================================
//  HttpUtil.h —— HTTP 协议层用到的一堆无状态小工具
//
//  为什么要单独抽一层：
//    这些函数（状态码文本、MIME 推断、日期格式化、百分号解码）既不属于
//    “请求”、也不属于“响应”，更不属于“解析状态机”，但三者都要用。
//    它们全部是纯函数（给定输入必得同一输出，不碰任何全局状态），
//    所以放在一起既方便复用，也方便单独验证。
// ============================================================================

#include <cstddef>
#include <string>

namespace net {
namespace http {

// ---------------------------------------------------------------------------
//  1. 状态码 → 原因短语（Reason Phrase）
//
//  状态行形如 "HTTP/1.1 200 OK"，那串 "OK" 就是原因短语。
//  它在 HTTP/1.1 里已经是“给人看的”、机器不该依赖的东西
//  （RFC 7230 §3.1.2 明确说客户端应当忽略它），但服务端还是要给对，
//  因为 curl / 浏览器 / 各类日志都会原样展示它。
// ---------------------------------------------------------------------------
const char* statusMessage(int code);

// ---------------------------------------------------------------------------
//  2. 按扩展名推断 Content-Type
//
//  返回的字符串已经带上了 charset（文本类），可以直接塞进响应头。
//  认不出来时返回 "application/octet-stream"（二进制流，让浏览器下载而不是渲染）。
//  真实项目会查一张完整的 MIME 表，这里只覆盖学习与演示够用的部分。
// ---------------------------------------------------------------------------
const char* mimeType(const std::string& path);

// ---------------------------------------------------------------------------
//  3. 生成 HTTP 日期
//
//  格式是 IMF-fixdate：Sun, 06 Nov 1994 08:49:37 GMT
//  （RFC 7231 §7.1.1.1，是 RFC 1123 日期格式的一个固定化版本）
//
//  两个必须注意的坑：
//    * gmtime() 返回的是指向**静态缓冲区**的指针，多线程下会互相踩。
//      MSVC 要用 gmtime_s，POSIX 要用 gmtime_r —— 它们把结果写进调用者给的
//      struct tm 里，是可重入的。
//    * 星期与月份的英文缩写必须自己拼。看着更省事的 strftime("%a, %d %b %Y ...")
//      会跟随 locale：在中文 Windows 上会输出“周日”而不是 "Sun"，
//      于是生成出一个不合法的日期头。（strftime 还有 %b 在中文下变“11月”的问题。）
// ---------------------------------------------------------------------------
std::string httpDate();

// ---------------------------------------------------------------------------
//  4. 百分号解码（URL Decoding）
//
//  "%20" → ' '，"%2F" → '/'，"+"/"→ ' '。
//  遇到非法转义（% 后面不是两位十六进制）返回 false，调用方应当直接回 400。
//
//  【安全提醒】解码会“凭空造出”在原文里看不见的字符：%2e%2e%2f 解码后就是 "../"。
//  所以任何安全校验（比如静态文件的目录穿越检查）都必须放在**解码之后**。
//  反过来做（先校验再解码）等于没校验 —— 这是 Web 安全里最经典的绕过手法之一。
// ---------------------------------------------------------------------------
bool urlDecode(const std::string& in, std::string& out);

// ---------------------------------------------------------------------------
//  5. 字符串小工具
// ---------------------------------------------------------------------------

// 转小写。头部字段名要统一小写成 key，见 HttpRequest 的说明。
//
// 注意这里刻意只处理 ASCII：HTTP 的头部字段名规范上就是 ASCII token，
// 跟标准库 std::tolower 的 locale 行为纠缠没有意义，反而容易出意外。
std::string toLower(std::string s);

// 去掉首尾的空白（空格 / 制表符 / \r / \n）。
// 头部字段名的前后空格是允许被忽略的（"Host : x" 与 "Host: x" 等价）。
std::string trim(const std::string& s);

// 在逗号分隔的 token 列表里查找某个 token，比较时不区分大小写。
// 用途：Connection 头的值可能是 "keep-alive, Upgrade" 这样的列表，
// 直接拿整串去 == 比较是查不到的（这是很常见的一个 bug）。
bool hasToken(const std::string& value, const std::string& token);

}  // namespace http
}  // namespace net
